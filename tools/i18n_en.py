bad = 0
for rel, reps in R.items():
    p = ROOT / rel
    s = p.read_text(encoding="utf-8")
    for rep in reps:
        old, new = rep[0], rep[1]
        n = rep[2] if len(rep) > 2 else 1
        c = s.count(old)
        if old == new:
            continue
        if c != n:
            print(f"MISMATCH {rel}: expected {n}, found {c}: {old[:70]!r}")
            bad += 1
            continue
        s = s.replace(old, new)
    p.write_text(s, encoding="utf-8")
sys.exit(1 if bad else 0)
