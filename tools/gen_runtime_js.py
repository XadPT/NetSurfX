#!/usr/bin/env python3
"""Embed the netsurf-switch JavaScript runtime shim (runtime.js) as a C
array, like `xxd -i`: gen/quickjs/runtime.js.inc (runtime_js, runtime_js_len).

    python3 tools/gen_runtime_js.py <netsurf dir> <out file>
Regenerated only when runtime.js is newer than the output.
"""
import os, sys

src, out = sys.argv[1], sys.argv[2]
js = os.path.join(src, 'content/handlers/javascript/quickjs/runtime.js')
if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(js):
    sys.exit(0)
data = open(js, 'rb').read()
lines = ['/* generated by tools/gen_runtime_js.py from runtime.js: do not edit */',
         'unsigned char runtime_js[] = {']
for i in range(0, len(data), 16):
    lines.append('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
lines += ['};', 'unsigned int runtime_js_len = %d;' % len(data)]
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(lines) + '\n')
print('generated', out, len(data), 'bytes')
